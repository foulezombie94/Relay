import {
  Type,
  Heading1,
  Heading2,
  Heading3,
  Heading4,
  List,
  ListOrdered,
  SquareCheck,
  ChevronRight,
  Lightbulb,
  Quote,
  Table2,
  Minus,
  Link2,
  Image,
  Video,
  Music2,
  Code2,
  Paperclip,
  Globe,
  ListTree,
  type LucideIcon,
} from "lucide-react";
import type { BlockKind } from "./blocks";
const icons = {
  paragraph: Type,
  heading1: Heading1,
  heading2: Heading2,
  heading3: Heading3,
  heading4: Heading4,
  bullet: List,
  number: ListOrdered,
  todo: SquareCheck,
  toggle: ChevronRight,
  callout: Lightbulb,
  quote: Quote,
  table: Table2,
  divider: Minus,
  link: Link2,
  image: Image,
  video: Video,
  audio: Music2,
  code: Code2,
  file: Paperclip,
  bookmark: Globe,
  toc: ListTree,
  toggleHeading1: Heading1,
  toggleHeading2: Heading2,
  toggleHeading3: Heading3,
} satisfies Record<BlockKind, LucideIcon>;
export function BlockIcon({ kind, size = 20 }: { kind: BlockKind; size?: number }) {
  const Icon = icons[kind];
  return <Icon size={size} strokeWidth={1.5} aria-hidden />;
}
