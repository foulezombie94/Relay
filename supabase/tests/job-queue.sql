begin;
set local statement_timeout='30s';
create temporary table queue_checks(label text);
grant select,insert on queue_checks to authenticated,service_role;
do $$
declare u uuid;w uuid;w2 uuid;obj uuid;a jsonb;b jsonb;c jsonb;x jsonb;y jsonb;body jsonb;
begin
 select id into u from auth.users order by created_at limit 1;
 if u is null then raise exception 'An Auth account is required';end if;
 perform set_config('request.jwt.claim.sub',u::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'role','authenticated')::text,true);
 w:=public.create_workspace('Queue integration fixture');w2:=public.create_workspace('Queue other fixture');
 select id into obj from public.objects where workspace_id=w and slug='people';
 body:=jsonb_build_object('object_id',obj,'rows_data',jsonb_build_array(jsonb_build_object('display_name','Queue fixture','email','queue-fixture@example.invalid')),
  'digest',repeat('a',64),'filename','queue.csv','mapping','{}'::jsonb,'duplicate_policy','skip','error_rows','[]'::jsonb);
 execute 'set local role authenticated';
 a:=public.enqueue_relay_job(w,'imports',body);b:=public.enqueue_relay_job(w,'imports',body);
 if a->>'id'<>b->>'id' then raise exception 'Enqueue duplicated';end if;
 begin perform public.relay_job_status(w2,(a->>'id')::uuid);raise exception 'Workspace isolation failed';exception when insufficient_privilege then null;end;
 begin perform public.relay_job_worker('metrics');raise exception 'Worker RPC exposed';exception when insufficient_privilege then null;end;
 begin execute 'select * from relay_private.jobs';raise exception 'Private payload exposed';exception when insufficient_privilege then null;end;
 insert into queue_checks values('dedupe, workspace isolation, private payload and worker RPC denied');
 b:=public.enqueue_relay_job(w,'imports',jsonb_set(body,'{digest}',to_jsonb(repeat('b',64))));
 execute 'set local role service_role';
 x:=public.relay_job_worker('claim','{"worker_id":"fixture-a","types":["imports"]}');
 y:=public.relay_job_worker('claim','{"worker_id":"fixture-b","types":["imports"]}');
 if x is null or y is null or x->>'id'=y->>'id' then raise exception 'Claims overlap';end if;
 if public.relay_job_worker('claim','{"worker_id":"fixture-c","types":["imports"]}') is not null then raise exception 'Running job reclaimed';end if;
 begin perform public.relay_job_worker('complete',jsonb_build_object('id',x->>'id','lease',gen_random_uuid()));raise exception 'Wrong lease accepted';exception when serialization_failure then null;end;
 insert into queue_checks values('exclusive claims and lease fencing');
 c:=public.relay_job_worker('execute',jsonb_build_object('id',x->>'id','lease',x->>'lease'));
 if (c->>'inserted')::int<>1 then raise exception 'Import was not applied';end if;
 c:=public.relay_job_worker('execute',jsonb_build_object('id',y->>'id','lease',y->>'lease'));
 if (c->>'skipped')::int<>1 then raise exception 'Duplicate recipient imported';end if;
 begin perform public.relay_job_worker('execute',jsonb_build_object('id',x->>'id','lease',x->>'lease'));raise exception 'Completed job executed again';exception when serialization_failure then null;end;
 execute 'reset role';
 if (select count(*) from public.records where workspace_id=w)<>1 or exists(select 1 from relay_private.jobs where workspace_id=w and (status<>'completed' or payload<>'{}')) then raise exception 'Atomic completion or payload erasure failed';end if;
 insert into queue_checks values('atomic effects/completion, duplicate skip, replay blocked and payload erased');
 execute 'set local role authenticated';
 a:=public.enqueue_relay_job(w,'imports',jsonb_set(body,'{digest}',to_jsonb(repeat('c',64))));
 execute 'set local role service_role';
 x:=public.relay_job_worker('claim','{"worker_id":"fixture-a","types":["imports"]}');
 perform public.relay_job_worker('fail',jsonb_build_object('id',x->>'id','lease',x->>'lease','retry_seconds',60,'code','provider_timeout'));
 if public.relay_job_worker('claim','{"worker_id":"fixture-b","types":["imports"]}') is not null then raise exception 'Backoff ignored';end if;
 execute 'reset role';update relay_private.jobs set run_at=now() where id=(x->>'id')::uuid;
 execute 'set local role service_role';
 y:=public.relay_job_worker('claim','{"worker_id":"fixture-b","types":["imports"]}');
 if (y->>'attempts')::int<>2 or y->>'lease'=x->>'lease' then raise exception 'Retry did not rotate lease';end if;
 execute 'reset role';update relay_private.jobs set leased_until=now()-interval '1 second' where id=(y->>'id')::uuid;
 execute 'set local role service_role';
 perform public.relay_job_worker('claim','{"worker_id":"fixture-c","types":["imports"]}');
 execute 'reset role';update relay_private.jobs set run_at=now() where id=(y->>'id')::uuid;
 execute 'set local role service_role';
 c:=public.relay_job_worker('claim','{"worker_id":"fixture-c","types":["imports"]}');
 begin perform public.relay_job_worker('complete',jsonb_build_object('id',y->>'id','lease',y->>'lease'));raise exception 'Expired worker accepted';exception when serialization_failure then null;end;
 perform public.relay_job_worker('fail',jsonb_build_object('id',c->>'id','lease',c->>'lease','permanent',true,'code','fixture_permanent'));
 execute 'reset role';
 if (select status from relay_private.jobs where id=(c->>'id')::uuid)<>'dead' then raise exception 'Permanent failure retried';end if;
 insert into queue_checks values('backoff, crash recovery, old worker rejected, terminal failures');
 perform set_config('request.jwt.claim.sub',gen_random_uuid()::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',gen_random_uuid(),'role','authenticated')::text,true);
 execute 'set local role authenticated';
 begin perform public.enqueue_relay_job(w,'imports',body);raise exception 'Non member enqueued';exception when insufficient_privilege then null;end;
 execute 'set local role anon';
 begin perform public.enqueue_relay_job(w,'imports',body);raise exception 'Anon enqueued';exception when insufficient_privilege then null;end;
 execute 'reset role';insert into queue_checks values('non-members and anonymous users denied');
end $$;
select * from queue_checks;
rollback;
